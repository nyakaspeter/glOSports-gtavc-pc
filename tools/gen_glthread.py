"""Generate shim/gl3thread_gen.inc: recording stubs for the GL functions re3 and
librw use, for the GL command thread in shim/gl3thread.cpp.

Usage: python3 tools/gen_glthread.py tools/gl_protos.txt > shim/gl3thread_gen.inc
gl_protos.txt holds glad.h typedef lines, e.g.
  typedef void (APIENTRYP PFNGLBINDBUFFERPROC)(GLenum target, GLuint buffer);
Every argument type is <= 32 bits on armhf, so commands store args as words.
"""
import re
import sys

PROTO = re.compile(r'typedef (.+?) \(APIENTRYP PFNGL([A-Z0-9]+)PROC\)\((.*)\);')

# Queued; all arguments by value (pointers in here are buffer offsets or
# already-persistent client arrays, see gl3thread.cpp).
BYVAL = '''ActiveTexture AttachShader BindFramebuffer BindRenderbuffer BindTexture
BindVertexArray BlendFunc Clear ClearColor CompileShader CopyTexSubImage2D
CullFace DeleteProgram DeleteShader DepthFunc DepthMask Disable
DisableVertexAttribArray DrawArrays Enable EnableVertexAttribArray
FramebufferRenderbuffer FramebufferTexture2D GenerateMipmap LinkProgram
ReadBuffer RenderbufferStorage StencilFunc StencilMask StencilOp TexParameterf
TexParameteri Uniform1i Uniform2f UniformBlockBinding UseProgram Viewport
PopDebugGroup VertexAttribPointer'''.split()
# Handwritten in gl3thread.cpp (payload copies, binding tracking, name pools).
MANUAL = '''BindBuffer BufferData BufferSubData TexImage2D CompressedTexImage2D
DeleteBuffers DeleteTextures DeleteFramebuffers DeleteRenderbuffers Uniform2fv
Uniform4fv UniformMatrix4fv ShaderSource BindAttribLocation PushDebugGroup
DrawElements PixelStorei GenBuffers GenTextures GenFramebuffers
GenRenderbuffers GenVertexArrays'''.split()
# Everything else returns data: run synchronously on the GL thread.


def camel(upper, names):
    for n in names:
        if n.upper() == upper:
            return n
    return None


def main():
    protos = []
    known = BYVAL + MANUAL
    for line in open(sys.argv[1]):
        m = PROTO.match(line.strip())
        if not m:
            continue
        ret, upper, args = m.groups()
        name = camel(upper, known) or SYNC_NAMES.get(upper)
        if name is None:
            sys.exit(f'unknown GL function {upper}: add it to a list in gen_glthread.py')
        params = [] if args.strip() == 'void' else [a.strip() for a in args.split(',')]
        decl = []
        for p in params:
            pm = re.match(r'(.*?)(\w+)$', p)
            decl.append((pm.group(1).strip(), pm.group(2)))
        protos.append((ret.strip(), name, decl))

    out = []
    w = out.append
    w('// Generated by tools/gen_glthread.py - do not edit.')
    w('struct RealGL {')
    for ret, name, decl in protos:
        w(f'\tPFNGL{name.upper()}PROC {name};')
    w('};')
    w('static RealGL real;')
    w('')
    for ret, name, decl in protos:
        sig = ', '.join(f'{t} {n}' for t, n in decl) or 'void'
        names = ', '.join(n for _, n in decl)
        if name in BYVAL:
            w(f'static void exec_{name}(Cmd *c)\n{{')
            for i, (t, n) in enumerate(decl):
                w(f'\t{t} {n}; memcpy(&{n}, &c->a[{i}], sizeof({n}));')
            w(f'\treal.{name}({names});\n}}')
            w(f'static void APIENTRY stub_{name}({sig})\n{{\n\tCmd *c = cmdAlloc();\n\tc->exec = exec_{name};')
            for i, (t, n) in enumerate(decl):
                w(f'\tc->a[{i}] = 0; memcpy(&c->a[{i}], &{n}, sizeof({n}));')
            w('\tcmdCommit();\n}')
        elif name in MANUAL:
            w(f'static {ret} APIENTRY stub_{name}({sig});	// in gl3thread.cpp')
            continue
        else:
            if ret == 'void':
                w(f'static void APIENTRY stub_{name}({sig})\n{{\n\tsyncRun([&]{{ real.{name}({names}); }});\n}}')
            else:
                w(f'static {ret} APIENTRY stub_{name}({sig})\n{{\n\t{ret} r;\n\tsyncRun([&]{{ r = real.{name}({names}); }});\n\treturn r;\n}}')
        w('')
    w('static void\ncaptureReal(void)\n{')
    for ret, name, decl in protos:
        w(f'\treal.{name} = glad_gl{name};')
    w('}\n')
    w('static void\ninstallStubs(void)\n{')
    for ret, name, decl in protos:
        w(f'\tglad_gl{name} = stub_{name};')
    w('}')
    print('\n'.join(out))


SYNC_NAMES = {n.upper(): n for n in '''CheckFramebufferStatus GetUniformLocation
CreateProgram CreateShader GetUniformBlockIndex GetString GetCompressedTexImage
GetFloatv GetIntegerv GetProgramInfoLog GetProgramiv GetShaderInfoLog
GetShaderiv GetTexImage ReadPixels'''.split()}

if __name__ == '__main__':
    main()
